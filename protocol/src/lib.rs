//! Shared wire protocol for esp-unlock.
//!
//! This crate is the single source of truth for the byte-level protocol
//! spoken between the host daemon and the ESP32 firmware over UART, and for
//! the HMAC challenge/response computation both sides rely on. Keeping it in
//! one `no_std`-compatible crate means the firmware and the host binary can
//! never silently drift apart on frame layout or tag computation.
//!
//! # Wire format
//!
//! Request (host -> device): `"CH"` followed by [`CHALLENGE_LEN`] random
//! bytes, [`FRAME_LEN`] bytes total.
//!
//! Response (device -> host), sent only after the device has waited up to
//! [`CONFIRM_TIMEOUT_SECS`] seconds for a physical button press:
//! - [`RESPONSE_CONFIRMED`] (`"ESPK"`) followed by [`TAG_LEN`] bytes of
//!   `HMAC-SHA256(secret, challenge)`, if the button was pressed in time.
//! - [`RESPONSE_DENIED`] (`"ESPN"`), if the button was not pressed before the
//!   timeout.
#![cfg_attr(not(test), no_std)]

use hmac::{Hmac, Mac};
use sha2::Sha256;

/// Length in bytes of the random challenge generated by the host.
pub const CHALLENGE_LEN: usize = 32;

/// Length in bytes of the HMAC-SHA256 tag returned by the device.
pub const TAG_LEN: usize = 32;

/// Two-byte marker that starts every request frame.
pub const REQUEST_PREFIX: [u8; 2] = *b"CH";

/// Total length in bytes of a request frame (`REQUEST_PREFIX` + challenge).
pub const FRAME_LEN: usize = REQUEST_PREFIX.len() + CHALLENGE_LEN;

/// Response header meaning "button pressed, tag follows".
pub const RESPONSE_CONFIRMED: [u8; 4] = *b"ESPK";

/// Response header meaning "button not pressed before the timeout".
pub const RESPONSE_DENIED: [u8; 4] = *b"ESPN";

/// How long the device waits for a physical button press before replying
/// with [`RESPONSE_DENIED`]. The host's own read timeout should be a little
/// longer than this to make sure it can still read a late `"ESPN"`.
pub const CONFIRM_TIMEOUT_SECS: u64 = 15;

/// Computes `HMAC-SHA256(secret, challenge)`.
///
/// `secret` may be any length; HMAC itself has no key-length restriction.
pub fn compute_tag(secret: &[u8], challenge: &[u8; CHALLENGE_LEN]) -> [u8; TAG_LEN] {
    let mut mac = <Hmac<Sha256> as Mac>::new_from_slice(secret)
        .expect("HMAC-SHA256 accepts keys of any length");
    mac.update(challenge);
    mac.finalize().into_bytes().into()
}

/// Verifies that `tag` is the correct `HMAC-SHA256(secret, challenge)`, in
/// constant time with respect to `tag`.
pub fn verify_tag(secret: &[u8], challenge: &[u8; CHALLENGE_LEN], tag: &[u8; TAG_LEN]) -> bool {
    let mut mac = <Hmac<Sha256> as Mac>::new_from_slice(secret)
        .expect("HMAC-SHA256 accepts keys of any length");
    mac.update(challenge);
    mac.verify_slice(tag).is_ok()
}

/// Byte-by-byte assembler for the `"CH"` + challenge request frame.
///
/// Feed it one byte at a time as they arrive off the wire (typically from a
/// non-blocking UART read); it resynchronizes on `"CH"` and returns the
/// completed challenge once a full frame has been assembled.
#[derive(Debug, Clone, Copy)]
pub struct FrameReader {
    buf: [u8; FRAME_LEN],
    filled: usize,
}

impl Default for FrameReader {
    fn default() -> Self {
        Self::new()
    }
}

impl FrameReader {
    /// Creates a fresh, empty frame reader.
    pub const fn new() -> Self {
        Self {
            buf: [0; FRAME_LEN],
            filled: 0,
        }
    }

    /// Feeds one byte into the assembler.
    ///
    /// Returns `Some(challenge)` once a full `"CH"` + challenge frame has
    /// been assembled, and resets internal state so the next call starts a
    /// fresh frame. Returns `None` otherwise, including while resynchronizing
    /// after bytes that don't match the `"CH"` prefix.
    pub fn push(&mut self, byte: u8) -> Option<[u8; CHALLENGE_LEN]> {
        match self.filled {
            0 if byte != REQUEST_PREFIX[0] => return None,
            1 if byte != REQUEST_PREFIX[1] => {
                // Resynchronize: this byte might itself be the start of the
                // next frame's prefix.
                self.filled = (byte == REQUEST_PREFIX[0]) as usize;
                return None;
            }
            _ => {}
        }

        self.buf[self.filled] = byte;
        self.filled += 1;
        if self.filled < FRAME_LEN {
            return None;
        }

        self.filled = 0;
        let mut challenge = [0u8; CHALLENGE_LEN];
        challenge.copy_from_slice(&self.buf[REQUEST_PREFIX.len()..]);
        Some(challenge)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn push_all(reader: &mut FrameReader, bytes: &[u8]) -> Option<[u8; CHALLENGE_LEN]> {
        let mut result = None;
        for &b in bytes {
            if let Some(challenge) = reader.push(b) {
                result = Some(challenge);
            }
        }
        result
    }

    #[test]
    fn frame_reader_assembles_a_clean_frame() {
        let mut reader = FrameReader::new();
        let challenge = [0x42u8; CHALLENGE_LEN];
        let mut frame = Vec::new();
        frame.extend_from_slice(&REQUEST_PREFIX);
        frame.extend_from_slice(&challenge);

        assert_eq!(push_all(&mut reader, &frame), Some(challenge));
    }

    #[test]
    fn frame_reader_ignores_noise_before_the_prefix() {
        let mut reader = FrameReader::new();
        let challenge = [0x7fu8; CHALLENGE_LEN];
        let mut frame = vec![0x00, 0xff, b'X', b'C']; // garbage, plus a false "C" start
        frame.extend_from_slice(&REQUEST_PREFIX);
        frame.extend_from_slice(&challenge);

        assert_eq!(push_all(&mut reader, &frame), Some(challenge));
    }

    #[test]
    fn frame_reader_resyncs_on_c_c_h() {
        // "CCH" + challenge must still be recognized: the second 'C' restarts
        // the prefix match instead of being treated as a desync byte.
        let mut reader = FrameReader::new();
        let challenge = [0x11u8; CHALLENGE_LEN];
        let mut frame = vec![b'C', b'C', b'H'];
        frame.extend_from_slice(&challenge);

        assert_eq!(push_all(&mut reader, &frame), Some(challenge));
    }

    #[test]
    fn frame_reader_handles_back_to_back_frames() {
        let mut reader = FrameReader::new();
        let first = [0xAAu8; CHALLENGE_LEN];
        let second = [0xBBu8; CHALLENGE_LEN];

        let mut frame1 = Vec::new();
        frame1.extend_from_slice(&REQUEST_PREFIX);
        frame1.extend_from_slice(&first);
        assert_eq!(push_all(&mut reader, &frame1), Some(first));

        let mut frame2 = Vec::new();
        frame2.extend_from_slice(&REQUEST_PREFIX);
        frame2.extend_from_slice(&second);
        assert_eq!(push_all(&mut reader, &frame2), Some(second));
    }

    #[test]
    fn frame_reader_returns_none_for_incomplete_frame() {
        let mut reader = FrameReader::new();
        let challenge = [0x5Au8; CHALLENGE_LEN];
        let mut frame = Vec::new();
        frame.extend_from_slice(&REQUEST_PREFIX);
        frame.extend_from_slice(&challenge);

        // All but the last byte: must not have completed yet.
        let (incomplete, last) = frame.split_at(frame.len() - 1);
        assert_eq!(push_all(&mut reader, incomplete), None);
        assert_eq!(push_all(&mut reader, last), Some(challenge));
    }

    #[test]
    fn verify_tag_accepts_a_tag_from_compute_tag() {
        let secret = b"test-secret";
        let challenge = [0x99u8; CHALLENGE_LEN];
        let tag = compute_tag(secret, &challenge);
        assert!(verify_tag(secret, &challenge, &tag));
    }

    #[test]
    fn verify_tag_rejects_wrong_secret() {
        let challenge = [0x01u8; CHALLENGE_LEN];
        let tag = compute_tag(b"correct-secret", &challenge);
        assert!(!verify_tag(b"wrong-secret", &challenge, &tag));
    }

    #[test]
    fn verify_tag_rejects_wrong_challenge() {
        let secret = b"test-secret";
        let tag = compute_tag(secret, &[0x01u8; CHALLENGE_LEN]);
        assert!(!verify_tag(secret, &[0x02u8; CHALLENGE_LEN], &tag));
    }

    #[test]
    fn verify_tag_rejects_corrupted_tag() {
        let secret = b"test-secret";
        let challenge = [0x03u8; CHALLENGE_LEN];
        let mut tag = compute_tag(secret, &challenge);
        tag[0] ^= 0xFF;
        assert!(!verify_tag(secret, &challenge, &tag));
    }

    /// Known-answer test against an independently computed HMAC-SHA256 value
    /// (`python3 -c "import hmac,hashlib;
    /// print(hmac.new(b'esp-unlock-test-key', bytes(32),
    /// hashlib.sha256).hexdigest())"`), so a future refactor can't silently
    /// swap in the wrong primitive.
    #[test]
    fn compute_tag_matches_known_answer() {
        let secret = b"esp-unlock-test-key";
        let challenge = [0u8; CHALLENGE_LEN];
        let tag = compute_tag(secret, &challenge);

        let expected =
            hex::decode("49fdd6bc963a5adf9977ee8fbbf34a62b43b063e04077b0abf7d2b3ceadffdf0")
                .expect("valid hex literal");
        assert_eq!(tag.as_slice(), expected.as_slice());
    }
}
